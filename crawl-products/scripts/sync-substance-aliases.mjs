#!/usr/bin/env node
/**
 * Regenerates lib/substance-aliases.data.mjs from Supply Smart's
 * docs/packages/database-api/domains/substance-aliases.json (KAN-285).
 *
 *   node crawl-products/scripts/sync-substance-aliases.mjs <path to substance-aliases.json>
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("usage: sync-substance-aliases.mjs <substance-aliases.json>");
  process.exit(1);
}
const data = JSON.parse(await fs.readFile(source, "utf8"));
const aliases = data.substance_aliases.map(({ alias, substance, form, kind }) => ({ alias, substance, form, kind }));
const labels = data.label_rules.map(({ label, substance, note }) => ({ label, substance, note }));
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "substance-aliases.data.mjs");
const header = `/**
 * Supply Smart substance aliases (KAN-285, version ${data.version}).
 *
 * GENERATED by crawl-products/scripts/sync-substance-aliases.mjs, do not edit by
 * hand. Source: supply-smart-mono docs/packages/database-api/domains/
 * substance-aliases.json (contract: substance-aliases.md next to it).
 *
 * SUBSTANCE_ALIASES: substance names Supply Smart merged away (merge) or turned
 * into a form under a keeper (form). A \`substance\` hint carrying one of them must
 * be sent as the keeper (and form), or Supply Smart recreates the duplicate.
 * SUBSTANCE_LABEL_RULES: label names that belong to a different substance than the
 * obvious one (mostly excipients: Magnesium Stearate is not Magnesium).
 */
`;
await fs.writeFile(target, `${header}
export const SUBSTANCE_ALIASES_VERSION = ${JSON.stringify(data.version)};

export const SUBSTANCE_ALIASES = Object.freeze(${JSON.stringify(aliases, null, 2)});

export const SUBSTANCE_LABEL_RULES = Object.freeze(${JSON.stringify(labels, null, 2)});
`);
console.log(`wrote ${target}: ${aliases.length} aliases, ${labels.length} label rules (version ${data.version})`);
